// Emits the C++ view of shared/editor/limits.json, the one place the world and
// editor limits are written down. TypeScript imports the JSON directly, so a
// TS-only build never needs this script or a compiler; MSBuild runs it before
// compiling (prevast_server.vcxproj, PrevastEditorContract) into ignored build
// output. Plain Node on purpose: the C++ build must not depend on tsx.
//
//   node tools/editor/generate-contract.mjs [--out <header>] [--check]
//
// --check exits 1 when the header on disk is missing or stale, without writing.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const LIMITS_PATH = resolve(root, 'shared/editor/limits.json');
export const DEFAULT_HEADER = resolve(root, 'build/generated/contract/editor_limits.h');

const INT32_MAX = 2147483647;

/** Throws when a value the C++ side narrows is not a non-negative safe integer. */
function integer(path, value) {
  if (!Number.isSafeInteger(value) || value < 0 || value > INT32_MAX)
    throw new Error(`${path} must be an integer in 0..${INT32_MAX}, got ${JSON.stringify(value)}`);
  return value;
}

function section(limits, name) {
  const value = limits[name];
  if (!value || typeof value !== 'object' || Array.isArray(value))
    throw new Error(`limits.json: "${name}" must be an object`);
  return value;
}

/** The header text for a parsed limits object. Deterministic: same input, same bytes. */
export function renderHeader(limits) {
  const world = section(limits, 'world');
  const project = section(limits, 'project');
  const overrides = section(limits, 'overrides');
  const lines = [];
  const constant = (group, key, value) =>
    lines.push(`\tinline constexpr int32_t ${key} = ${integer(`${group}.${key}`, value)};`);

  lines.push('// GENERATED by tools/editor/generate-contract.mjs from shared/editor/limits.json.');
  lines.push('// Do not edit; change the JSON. Checked into nothing: build output only.');
  lines.push('#ifndef PREVAST_CONTRACT_EDITOR_LIMITS_H');
  lines.push('#define PREVAST_CONTRACT_EDITOR_LIMITS_H');
  lines.push('');
  lines.push('#include <cstdint>');
  lines.push('');
  lines.push('namespace EditorContract {');
  constant('root', 'contractVersion', limits.contractVersion);
  lines.push('');
  lines.push('namespace World {');
  for (const [key, value] of Object.entries(world)) constant('world', key, value);
  lines.push('} // namespace World');
  lines.push('');
  lines.push('namespace Project {');
  for (const [key, value] of Object.entries(project)) constant('project', key, value);
  lines.push('} // namespace Project');
  lines.push('');
  lines.push('namespace Overrides {');
  for (const [key, value] of Object.entries(overrides)) constant('overrides', key, value);
  lines.push('} // namespace Overrides');
  lines.push('} // namespace EditorContract');
  lines.push('');
  lines.push('#endif // PREVAST_CONTRACT_EDITOR_LIMITS_H');
  lines.push('');
  return lines.join('\n');
}

export function loadLimits(path = LIMITS_PATH) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function main(argv) {
  const outIndex = argv.indexOf('--out');
  const out = outIndex >= 0 ? resolve(argv[outIndex + 1]) : DEFAULT_HEADER;
  const text = renderHeader(loadLimits());
  const current = existsSync(out) ? readFileSync(out, 'utf8') : null;
  if (argv.includes('--check')) {
    if (current !== text) {
      console.error(`${out} is missing or stale; run node tools/editor/generate-contract.mjs`);
      process.exit(1);
    }
    return;
  }
  // Only rewrite on change so MSBuild does not recompile everything that includes it.
  if (current === text) return;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`editor contract: wrote ${out}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`editor contract: ${error.message}`);
    process.exit(1);
  }
}
