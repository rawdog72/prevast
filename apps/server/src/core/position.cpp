#include "core/otpch.h"

#include "core/position.h"

#include <iomanip>

std::ostream& operator<<(std::ostream& os, const Position& pos)
{
	os << "( " << std::setw(5) << std::setfill('0') << pos.x;
	os << " / " << std::setw(5) << std::setfill('0') << pos.y;
	os << " )";
	return os;
}
